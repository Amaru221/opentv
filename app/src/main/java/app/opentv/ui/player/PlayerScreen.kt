/**
 * The playback timeline, above the buttons.
 *
 * A live channel has no duration, so the caller only draws this when the media item is seekable â€”
 * for a recording or a catch-up programme. Position is polled rather than observed because
 * ExoPlayer has no position flow, and half a second is enough for a clock that reads in seconds.
 */
@OptIn(UnstableApi::class)
@Composable
private fun PlayerSeekBar(player: ExoPlayer, seekable: Boolean) {
    var position by remember { mutableLongStateOf(0L) }
    var duration by remember { mutableLongStateOf(0L) }
    var scrubbing by remember { mutableStateOf(false) }

    LaunchedEffect(player) {
        while (true) {
            if (!scrubbing) {
                position = player.currentPosition.coerceAtLeast(0L)
                val d = player.duration
                duration = if (d == C.TIME_UNSET) 0L else d.coerceAtLeast(0L)
            }
            delay(500)
        }
    }

    Row(Modifier.fillMaxWidth(), verticalAlignment = Alignment.CenterVertically) {
        Text(
            formatClock(position),
            style = MaterialTheme.typography.labelLarge,
            color = Color.White.copy(alpha = 0.85f),
        )
        Slider(
            value = if (duration > 0L) (position.toFloat() / duration).coerceIn(0f, 1f) else 0f,
            onValueChange = { fraction ->
                scrubbing = true
                if (duration > 0L) {
                    position = (fraction * duration).toLong()
                    player.seekTo(position)
                }
            },
            onValueChangeFinished = { scrubbing = false },
            // A live stream without a seekable window still gets the bar, but no thumb to drag:
            // its duration is unknown, so any scrubbing would be a lie.
            enabled = seekable && duration > 0L,
            colors = SliderDefaults.colors(
                thumbColor = Color.White,
                activeTrackColor = MaterialTheme.colorScheme.primary,
                inactiveTrackColor = Color.White.copy(alpha = 0.28f),
            ),
            modifier = Modifier.weight(1f).padding(horizontal = 12.dp),
        )
        Text(
            if (seekable && duration > 0L) formatClock(duration) else stringResource(R.string.player_live),
            style = MaterialTheme.typography.labelLarge,
            color = Color.White.copy(alpha = 0.85f),
        )
    }
}

/** 1:05 or 1:02:05 â€” no leading zero on the hour, which is how every player shows it. */
private fun formatClock(millis: Long): String {
    val total = (millis / 1000L).coerceAtLeast(0L)
    val hours = total / 3600L
    val minutes = (total % 3600L) / 60L
    val seconds = total % 60L
    return if (hours > 0L) {
        String.format(Locale.US, "%d:%02d:%02d", hours, minutes, seconds)
    } else {
        String.format(Locale.US, "%d:%02d", minutes, seconds)
    }
}

